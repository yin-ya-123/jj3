import streamlit as st

# (指标名, 全称, 含义说明, 用途/口径)
GLOSSARY = [
    (
        "MA",
        "移动平均线（Moving Average）",
        "N 日收盘价的算术平均，反映一段时间内的平均成本，平滑短期波动。",
        "MA5/10/20/60 分别代表 5/10/20/60 日均价；均线多头排列（短期在上）常视为强势信号。",
    ),
    (
        "EMA",
        "指数移动平均线（Exponential Moving Average）",
        "对近期价格赋予更高权重的均值，比 MA 对价格变化更敏感。",
        "本项目采用 ewm(adjust=False)，首根起算；用于 MACD 等衍生指标。",
    ),
    (
        "MACD",
        "指数平滑异同移动平均线（Moving Average Convergence Divergence）",
        "由快慢 EMA 之差（DIF）及其平滑（DEA）组成，反映趋势动能与拐点。",
        "DIF=EMA12-EMA26；DEA=DIF 的 9 日 EMA；MACD 柱=2×(DIF-DEA)。金叉/死叉与柱体变化是常用信号。",
    ),
    (
        "RSI",
        "相对强弱指标（Relative Strength Index）",
        "衡量一段时期内涨跌力量的强弱，取值 0-100。",
        "RSI(14) 高于 70 常视为超买、低于 30 常视为超卖；本项目单边涨=100、跌=0、平=50。",
    ),
    (
        "KDJ",
        "随机指标（Stochastic Oscillator）",
        "通过收盘价在近期高低区间的位置判断超买超卖，K、D、J 三线配合使用。",
        "K/D 采用 ewm(alpha=1/3) 平滑；J 线反映短线强弱，高位钝化与低位金叉是常见用法。",
    ),
    (
        "BOLL",
        "布林带（Bollinger Bands）",
        "以中轨（MA20）为中心、上下轨为 ±2 倍标准差构成的通道，衡量价格波动区间。",
        "本项目标准差用总体标准差（ddof=0）；价格触上轨偏强、触下轨偏弱，收口预示变盘。",
    ),
    (
        "ATR",
        "平均真实波幅（Average True Range）",
        "度量一段时间内价格的平均波动幅度，用于评估风险与设置止损。",
        "采用 Wilder 平滑（14 日）；ATR 越大波动越剧烈、风险越高。",
    ),
    (
        "量比",
        "当日成交量与近期均量的比值",
        "衡量当日成交活跃度相对历史的放大/缩小程度。",
        "量比 = 当日成交量 / 前 5 日均量；量比 ≥1.5 视为放量，<0.7 视为缩量。",
    ),
    (
        "均量",
        "N 日平均成交量（ma_vol_5/10）",
        "平滑成交量波动，观察成交量的中期趋势。",
        "均量上行配合价格上涨通常代表资金持续流入。",
    ),
    (
        "换手率",
        "当日成交股数占流通股本的比例",
        "反映股票交易的活跃程度与筹码交换速度。",
        "换手率持续放大且价格配合，常意味着关注度提升；本项目提供换手率均线与比值（turn_ratio）。",
    ),
    (
        "量价配合",
        "成交量与价格走势的一致性判断",
        "判断上涨/下跌是否获得成交量确认，识别放量突破或缩量调整。",
        "状态分为：放量上涨 / 放量下跌 / 温和放量上涨 / 缩量下跌 / 量平价稳。",
    ),
    (
        "支撑位",
        "价格下行时可能获得支撑的价位",
        "历史上多次止跌的价位，或技术指标（BOLL 下轨、MA、整数关口）所在位置。",
        "跌破支撑可能加速下行；支撑越多次被验证越有效。",
    ),
    (
        "压力位",
        "价格上行时可能遭遇抛压的价位",
        "历史上多次见顶回落的价位，或技术指标（BOLL 上轨、MA、整数关口）所在位置。",
        "突破压力可能打开上行空间；压力与支撑常相互转化。",
    ),
    (
        "综合评分",
        "多指标信号加权得到的 0-100 分",
        "汇总趋势、均线、动能、量价、波动等信号，给出量化强弱评价。",
        "≥60 偏多、≤40 偏空；信号分看多/中性/看空，风险分低/中/高；样本不足输出「数据不足」。",
    ),
]


def render_indicator_glossary() -> None:
    """在页面中渲染「指标名词解释」可折叠区"""

    with st.expander("📖 指标名词解释（点击展开）", expanded=False):
        st.caption("本系统技术指标全部由 pandas 本地计算，口径与常用定义一致，结果可复现。")

        columns = st.columns(3)

        for index, (name, full, meaning, usage) in enumerate(GLOSSARY):
            with columns[index % 3]:
                st.markdown(f"**{name} — {full}**")
                st.markdown(f"含义：{meaning}")
                st.markdown(f"口径/用途：{usage}")
                st.divider()
